        Table.ToDictionary(e => e.Id);

    /// <summary>Every id the game can spawn.</summary>
    public static IReadOnlyList<Entry> All => Table;

    /// <summary>Whether the game has a spawn function for this id.</summary>
    public static bool IsKnown(int id) => ById.ContainsKey(id);

    public static Entry? Lookup(int id) => ById.TryGetValue(id, out var e) ? e : null;

    /// <summary>The object's asset name, or null when it does not load one.</summary>
    /// <remarks>
    /// Only 116 ids have one and it is unevenly trustworthy. To identify what an
    /// object <i>is</i>, use <see cref="ClassOf"/>.
    /// </remarks>
    public static string? NameOf(int id) => ById.TryGetValue(id, out var e) ? e.Name : null;

    /// <summary>
    /// The object's engine class — <c>Spring</c>, <c>DashPanel</c> — or null when
    /// the id is not recovered.
    /// </summary>
    /// <remarks>This is the field to match behaviours on.</remarks>
    public static string? ClassOf(int id) => ById.TryGetValue(id, out var e) ? e.Class : null;

    /// <summary>Whether an id is an instance of the given engine class.</summary>
    public static bool Is(int id, string className) =>
        ById.TryGetValue(id, out var e) && e.Class == className;

    /// <summary>Every id whose engine class is the given one.</summary>
    public static IEnumerable<int> IdsOfClass(string className) =>
        Table.Where(e => e.Class == className).Select(e => e.Id);

    /// <summary>
    /// A stable label for an id — its class when known, then its asset name,
    /// otherwise the handler it shares with its siblings.
    /// </summary>
    public static string Describe(int id)
    {
        if (!ById.TryGetValue(id, out var e)) return $"obj{id}";
        return e.Class ?? e.Name ?? $"obj@{e.Handler:X6}";
    }

    /// <summary>Ids that are variants of the same object, including this one.</summary>
    public static IEnumerable<Entry> Family(int id) =>
        ById.TryGetValue(id, out var e)
            ? Table.Where(t => t.Handler == e.Handler)
            : [];
