namespace Sonic4Episode2.Core.Assets;

/// <summary>
/// What the object ids in a stage's <c>.EV</c> records actually refer to.
/// </summary>
/// <remarks>
/// Recovered from the game's own spawn dispatch table at
/// <c>Sonic.exe:0x007031C8</c> — 803 slots indexed directly by object id, of
/// which 714 hold a spawn function. Ids that share a function are the same
/// object with a different variant: the handler subtracts its own base id to get
/// a variant number, so ids 661-668 are one object in eight flavours.
/// <para>
/// <b><see cref="Entry.Class"/> is the object's real identity, read from the
/// linker.</b> The Android developer build carries the same table with every
/// slot named, so 679 ids resolve to their engine class — <c>Spring</c>,
/// <c>DashPanel</c>, <c>GoalPanel</c> — instead of being guessed at. That covers
/// <b>13,563 of the 13,588 placements</b> in the game's 30 acts (99.8%); the 25
/// that do not are ids 669-671 in <c>G_ZONEF</c>, whose slots the Android build
/// leaves empty, and they stay <b>not recovered</b>.
/// </para>
/// <para>
/// The base is anchored on two ids proven from placement data alone: id 443 is
/// the start marker and id 520 the goal (<c>docs/FORMAT-EVENTS.md</c>). Exactly
/// one alignment puts <c>GmGmkStartInit</c> on 443 and <c>GmGmkGoalPanelInit</c>
/// on 520 at the same time, which is what makes this a reading rather than a
/// guess. Regenerate with <c>tools/dispatch.py csharp</c>.
/// </para>
/// <para>
/// <see cref="Entry.Name"/> is a different thing and is kept: it is the
/// <i>asset</i> an object loads, scraped from string immediates in the Windows
/// build, and it is unevenly trustworthy — only 116 ids have one, and a shared
/// loader can leak a name belonging to another object. Where both exist they
/// agree on meaning but not always on wording, because they describe different
/// things: id 312 loads a <c>CandleStick</c> and its class is <c>LightMask</c>.
/// <b>Match on <see cref="Class"/>, not on <see cref="Name"/></b> — doing the
/// latter is what put springs on an id this game never places.
/// </para>
/// <para>
/// Sizes come from the argument each handler passes to the shared object
/// constructor at <c>0x004834C0</c>, so they are the engine's own instance sizes.
/// </para>
/// </remarks>
public static class ObjectCatalog
{
    /// <summary>
    /// Scheduler priority every spawned object runs at, read from the constructor
    /// calls — 270 of the 294 handlers that could be read pass this value.
    /// </summary>
    public const int Priority = 0x1500;

    /// <summary>One object id.</summary>
    /// <param name="Id">The id as it appears in an <c>.EV</c> record.</param>
    /// <param name="Handler">Spawn function address; equal for variants of one object.</param>
    /// <param name="Size">Instance size in bytes, or 0 when it could not be read.</param>
    /// <param name="Class">
    /// The engine's own class for this id, read from the symbolized build —
    /// <c>Spring</c>, <c>DashPanel</c>, <c>GoalPanel</c>. This is the identity to
    /// match on. Null on the 25 <c>G_ZONEF</c> placements that are not recovered.
    /// </param>
    /// <param name="Name">
    /// Asset name, when the object loads one. Scraped from the stripped Windows
    /// build and only partly trustworthy — see the type's remarks.
    /// </param>
    /// <param name="Direct">
    /// True when the asset name was read from the handler itself rather than from
    /// a function it calls. A false here means that name is a reasonable guess,
    /// not a reading. Says nothing about <see cref="Class"/>, which is read.
    /// </param>
    public readonly record struct Entry(
        int Id, int Handler, int Size, string? Class, string? Name, bool Direct);

